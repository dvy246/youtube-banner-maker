export function listAestheticBackgrounds(category?: string): AestheticBackground[] {
  if (!category || category === "all") {
    return AESTHETIC_BACKGROUNDS;
  }
  return AESTHETIC_BACKGROUNDS.filter((b) => b.category === category);
}

export function getAestheticBackground(id: string): AestheticBackground | undefined {
  return AESTHETIC_BACKGROUNDS.find((b) => b.id === id);
}
